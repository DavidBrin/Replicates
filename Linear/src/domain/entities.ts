/**
 * The domain vocabulary.
 *
 * Everything in this file is a plain type or a frozen constant — no imports,
 * no I/O, no framework. It is the one module both the server and the browser
 * are allowed to share wholesale, and the reason the repositories, the
 * authorization policy and the UI can disagree about almost anything except
 * what an Issue *is*.
 *
 * Field names follow Linear's own GraphQL schema wherever the concept exists
 * there (`identifier`, `sortOrder`, `stateType`, `priority` as an int), so the
 * research notes in `research/03-data-model.md` read as a spec for this file
 * rather than as a translation of it. Deviations are marked where they occur.
 */

/* ============================================================ identifiers = */

/**
 * Ids are opaque strings with a type prefix (`iss_`, `tem_`, …), generated by
 * the application rather than the database.
 *
 * Two reasons, both practical. An id that exists before the row does lets a
 * client render an optimistic issue and then reconcile it by id instead of by
 * position — the thing that makes creating an issue feel instant. And a
 * prefixed id makes a mis-wired foreign key obvious in a log line, which an
 * integer sequence never does.
 */
export type Id<Prefix extends string = string> = string & { __prefix?: Prefix };

export type UserId = Id<"usr">;
export type WorkspaceId = Id<"wsp">;
export type TeamId = Id<"tem">;
export type IssueId = Id<"iss">;
export type ProjectId = Id<"prj">;
export type LabelId = Id<"lbl">;
export type StateId = Id<"sta">;
export type CommentId = Id<"cmt">;
export type MilestoneId = Id<"mil">;
export type ViewId = Id<"viw">;

/** ISO-8601 UTC. Stored as `text` so one SQL dialect serves both engines. */
export type Timestamp = string;

