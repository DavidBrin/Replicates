/**
 * Project membership — and a deliberate divergence from Linear.
 *
 * In Linear, project membership carries **no permissions at all**: lead and
 * member are ownership and notification signals, while the right to see or
 * edit a project comes entirely from membership of the project's *teams*
 * (`research/02-features.md` §9).
 *
 * This clone makes project membership load-bearing instead, because the brief
 * asks for it directly — people added to a project must be able to add to and
 * edit that project. So `ProjectMember` is consulted by the authorization
 * policy: being a member grants edit on the project and its issues, and a
 * guest sees only the projects they were added to. Linear's behaviour is
 * recoverable by ignoring this table in the policy; nothing else depends on
 * the distinction.
 */
export const PROJECT_ROLES = ["lead", "member"] as const;
export type ProjectRole = (typeof PROJECT_ROLES)[number];

