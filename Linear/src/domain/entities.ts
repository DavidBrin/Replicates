/* ================================================================ issues == */

export interface Issue {
  readonly id: IssueId;
  readonly teamId: TeamId;
  /** Per-team monotonic counter. `identifier` is `team.key + "-" + number`. */
  readonly number: number;
  readonly title: string;
  /** Markdown. Rendered, never dangerously injected. */
  readonly description: string;
  readonly stateId: StateId;
  readonly priority: Priority;
  readonly assigneeId: UserId | null;
  readonly creatorId: UserId;
  readonly projectId: ProjectId | null;
  readonly milestoneId: MilestoneId | null;
  readonly parentId: IssueId | null;
  readonly estimate: number | null;
  readonly dueDate: string | null;
  /**
   * Manual order, as a base-62 fractional index — a *string*, not a float.
   *
   * Linear itself uses `Float`, and float midpointing is the obvious choice:
   * `(prev + next) / 2` writes one row per drag. It also has a cliff. A double
   * carries ~52 bits of mantissa, so repeatedly dropping an issue into the
   * *same* gap exhausts precision in about 50 moves, after which
   * `(a + b) / 2 === a` and the order silently collapses — no error, just two
   * issues that will not stay apart. Linear ships a rebalancing pass to cope.
   *
   * A variable-length string key has no cliff: the midpoint of two adjacent
   * keys is one character longer, forever. The trade is one extra byte per
   * reorder against deleting the rebalancer from the critical path
   * (`research/03-data-model.md` §3.2). {@link module:domain/ordering} holds
   * the implementation.
   *
   * The key is workspace-wide, exactly as in Linear: grouping by status or
   * assignee partitions one global order rather than maintaining a key per
   * view. Comparisons must be byte-wise — see the collation note in
   * `schema.sql`, which is the likeliest place for this to go quietly wrong.
   */
  readonly sortOrder: string;
  /** Only set when the issue has a parent; null otherwise. */
  readonly subIssueSortOrder: string | null;
  readonly createdAt: Timestamp;
  readonly updatedAt: Timestamp;
  /**
   * Category-transition stamps — and they are *cleared*, not sticky.
   *
   * Linear stamps `completedAt` when an issue enters any `completed` state and
   * **clears it again** if the issue later moves back out of that category, so
   * a Backlog → Done → In Progress round trip ends with `completedAt` null.
   * They also do not re-stamp on a move *within* a category (In Progress → In
   * Review leaves `startedAt` alone).
   *
   * This is the rule a clone is most likely to get wrong, because deriving the
   * stamps from the activity log — "the timestamp of the last transition into
   * a completed state" — looks equivalent and is not: it silently resurrects
   * the old value and corrupts every cycle-time and progress rollup that reads
   * it (`research/02-features.md` §2).
   */
  readonly startedAt: Timestamp | null;
  readonly completedAt: Timestamp | null;
  readonly canceledAt: Timestamp | null;
  readonly archivedAt: Timestamp | null;
  readonly triagedAt: Timestamp | null;
}

