/* ============================================================== priority == */

/**
 * Linear's integer enum, verbatim — including the part that trips people up:
 * `0` is *No priority*, and it sorts **after** Low rather than before Urgent.
 * Sorting by the raw integer puts unprioritised issues at the top, which is
 * exactly wrong; `PRIORITY_SORT_RANK` is what the comparators use.
 */
export const PRIORITY_VALUES = [0, 1, 2, 3, 4] as const;
export type Priority = (typeof PRIORITY_VALUES)[number];

export const PRIORITY_NONE = 0 satisfies Priority;
export const PRIORITY_URGENT = 1 satisfies Priority;
export const PRIORITY_HIGH = 2 satisfies Priority;
export const PRIORITY_MEDIUM = 3 satisfies Priority;
export const PRIORITY_LOW = 4 satisfies Priority;

export const PRIORITY_LABELS: Readonly<Record<Priority, string>> = Object.freeze(
  {
    0: "No priority",
    1: "Urgent",
    2: "High",
    3: "Medium",
    4: "Low",
  },
);

/** Ascending sort order: Urgent, High, Medium, Low, then No priority last. */
export const PRIORITY_SORT_RANK: Readonly<Record<Priority, number>> =
  Object.freeze({ 1: 0, 2: 1, 3: 2, 4: 3, 0: 4 });

